#!/usr/bin/env node
// Generates packages/ui/src/icons/glyphs.ts from Google's Material Symbols Rounded SVG sources
// (Apache-2.0). Run once when the icon vocabulary in packages/design-tokens/src/icons.ts changes.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsSource = readFileSync(path.join(ROOT, 'packages/design-tokens/src/icons.ts'), 'utf8');
const names = [...new Set([...iconsSource.matchAll(/:\s*'([a-z0-9_]+)'/g)].map((m) => m[1]))];

const BASE = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web';

async function fetchSvg(name, variant) {
  const file = variant === 'fill' ? `${name}_fill1_24px.svg` : `${name}_24px.svg`;
  const res = await fetch(`${BASE}/${name}/materialsymbolsrounded/${file}`);
  if (!res.ok) return null;
  const svg = await res.text();
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24';
  const d = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]).join(' ');
  if (!d) return null;
  return { viewBox, d };
}

const out = {};
const missing = [];
for (const name of names) {
  const outline = await fetchSvg(name, 'outline');
  if (!outline) {
    missing.push(name);
    continue;
  }
  const fill = await fetchSvg(name, 'fill');
  out[name] = { outline, fill: fill ?? undefined };
  process.stdout.write(`✓ ${name}\n`);
}

const header = `// GENERATED by scripts/fetch-material-symbols.mjs — do not edit by hand.
// Source: Material Symbols Rounded (Google, Apache License 2.0) · wght 400 · opsz 24.
export interface Glyph { viewBox: string; d: string }
export interface GlyphSet { outline: Glyph; fill?: Glyph }
export const GLYPHS: Record<string, GlyphSet> = ${JSON.stringify(out, null, 2)};
`;
mkdirSync(path.join(ROOT, 'packages/ui/src/icons'), { recursive: true });
writeFileSync(path.join(ROOT, 'packages/ui/src/icons/glyphs.ts'), header);
console.log(`\nWrote ${Object.keys(out).length} glyphs. Missing: ${missing.join(', ') || 'none'}`);
